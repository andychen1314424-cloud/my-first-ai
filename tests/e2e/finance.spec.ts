import { test, expect } from '@playwright/test';

test('real-account rule proposals require confirmation and empty spending cannot imply funded reserves', async ({ page, request }) => {
  await page.goto('/#/finance/analysis');
  await expect(page.getByText('无法估算，请输入有效的必要月支出。', { exact: true })).toBeVisible();
  await expect(page.locator('.runway-num')).toContainText('—');
  const essential = page.getByPlaceholder('请输入必要月支出');
  await essential.fill('100');
  await expect(page.locator('.runway-num')).not.toContainText('—');
  await essential.fill('0');
  await expect(page.locator('.runway-num')).toContainText('—');

  const account = await (await request.post('/api/finance/accounts', { data: { name: '规则识别合成微信', group: 'cash', kind: 'wechat', openingBalance: 10000 } })).json();
  await page.goto('/#/finance/transactions');
  await page.reload();
  await expect(page.locator('.skeleton')).toHaveCount(0);
  await page.getByRole('button', { name: /记一笔/ }).first().click();
  const dialog = page.getByRole('dialog', { name: '记一笔', exact: true });
  const proposal = dialog.getByPlaceholder('例如：午饭 38 微信');
  await proposal.fill('午饭 12.345 微信');
  await dialog.getByRole('button', { name: '识别', exact: true }).click();
  await expect(dialog.getByLabel('金额（元）')).toHaveValue('');
  const before = (await (await request.get('/api/finance/snapshot')).json()).transactions.length;
  await proposal.fill('午饭 12.34 微信');
  await dialog.getByRole('button', { name: '识别', exact: true }).click();
  await expect(dialog.getByText('规则识别合成微信', { exact: true })).toBeVisible();
  await expect(dialog.getByText('餐饮', { exact: true })).toBeVisible();
  expect((await (await request.get('/api/finance/snapshot')).json()).transactions.length).toBe(before);
  await dialog.getByRole('button', { name: '保存', exact: true }).click();
  await expect(dialog).toBeHidden();
  const saved = (await (await request.get('/api/finance/snapshot')).json()).transactions.find((t: { accountId: string }) => t.accountId === account.id);
  expect(saved.amount).toBe(1234);
  expect(saved.categoryId).toBe('e_food');
  expect(saved.source).toBe('manual');
});

test('real ledger UI creates an account, saves cents, survives closing the tab, edits and deletes', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  const name = `浏览器现金-${Date.now()}`;
  const note = `闭环验证-${Date.now()}`;
  await page.goto('/#/finance/assets');
  await expect(page.getByRole('heading', { name: 'ZX Finance' })).toBeVisible();
  await page.getByRole('button', { name: '添加账户', exact: true }).click();
  const accountDialog = page.getByRole('dialog', { name: '添加账户' });
  await accountDialog.getByLabel('账户类型').selectOption('cash');
  await accountDialog.getByLabel('名称', { exact: true }).fill(name);
  await accountDialog.getByLabel('初始余额（元）').fill('1000.00');
  await accountDialog.getByRole('button', { name: '添加', exact: true }).click();
  await expect(accountDialog).toBeHidden();
  await expect(page.getByText(name, { exact: true })).toBeVisible();
  const initial = await (await request.get('/api/finance/snapshot')).json();
  expect(initial.isDemo).toBe(false);
  const account = initial.accounts.find((a: { name: string }) => a.name === name);
  const category = initial.categories.find((c: { id: string }) => c.id === 'e_food');
  expect(account.balance).toBe(100000);
  await page.getByRole('button', { name: /记一笔/ }).first().click();
  let dialog = page.getByRole('dialog', { name: '记一笔', exact: true });
  await dialog.getByLabel('金额（元）').fill('38.25');
  await dialog.getByRole('button', { name: '下一步' }).click();
  await dialog.getByRole('radio', { name: category.name, exact: true }).click();
  await dialog.getByLabel('支付账户').selectOption(account.id);
  await dialog.getByRole('button', { name: '下一步' }).click();
  await dialog.getByLabel('备注（可选）').fill(note);
  await dialog.getByRole('button', { name: '保存', exact: true }).click();
  await expect(dialog).toBeHidden();
  const saved = await (await request.get('/api/finance/snapshot')).json();
  expect(saved.accounts.find((a: { id: string }) => a.id === account.id).balance).toBe(96175);
  expect(saved.transactions.filter((x: { note: string }) => x.note === note)).toHaveLength(1);

  const context = page.context();
  const reopened = await context.newPage();
  reopened.on('pageerror', (e) => errors.push(e.message));
  await page.close();
  page = reopened;
  await page.goto('/#/finance/transactions');
  const record = page.getByRole('button').filter({ hasText: note });
  await expect(record).toBeVisible();
  await record.click();
  dialog = page.getByRole('dialog', { name: '编辑记录', exact: true });
  await dialog.getByLabel('金额（元）').fill('20.00');
  await dialog.getByRole('button', { name: '下一步' }).click();
  await dialog.getByRole('button', { name: '下一步' }).click();
  await dialog.getByRole('button', { name: '保存修改', exact: true }).click();
  await expect(dialog).toBeHidden();
  const edited = await (await request.get('/api/finance/snapshot')).json();
  expect(edited.accounts.find((a: { id: string }) => a.id === account.id).balance).toBe(98000);
  await record.click();
  dialog = page.getByRole('dialog', { name: '编辑记录', exact: true });
  await dialog.getByRole('button', { name: '下一步' }).click();
  await dialog.getByRole('button', { name: '下一步' }).click();
  await dialog.getByRole('button', { name: '删除这笔记录', exact: true }).click();
  const confirm = page.getByRole('dialog', { name: '删除这笔记录？', exact: true });
  await confirm.getByRole('button', { name: '取消', exact: true }).click();
  await expect(dialog).toBeVisible();
  expect((await (await request.get('/api/finance/snapshot')).json()).transactions.some((x: { note: string }) => x.note === note)).toBe(true);
  await dialog.getByRole('button', { name: '删除这笔记录', exact: true }).click();
  await page.getByRole('dialog', { name: '删除这笔记录？', exact: true }).getByRole('button', { name: '删除', exact: true }).click();
  await expect(dialog).toBeHidden();
  const final = await (await request.get('/api/finance/snapshot')).json();
  expect(final.accounts.find((a: { id: string }) => a.id === account.id).balance).toBe(100000);
  expect(final.transactions.some((x: { note: string }) => x.note === note)).toBe(false);
  expect(errors).toEqual([]);
  await page.screenshot({ path: 'test-results/finance-real-desktop.png', fullPage: true });
});

test('390px navigation, financial pages and three-step entry remain usable without horizontal overflow', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.setViewportSize({ width: 390, height: 844 });
  for (const route of ['/', '/assistant', '/finance', '/finance/assets', '/finance/transactions', '/finance/budget', '/finance/debts', '/finance/analysis', '/lab', '/history', '/settings']) {
    await page.goto('/#' + route);
    await expect(page.locator('#main')).toBeVisible();
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  }
  const name = `手机测试现金-${Date.now()}`;
  const response = await request.post('/api/finance/accounts', { data: { name, group: 'cash', kind: 'cash', openingBalance: 10000 } });
  expect(response.status()).toBe(201);
  const account = await response.json();
  const snapshot = await (await request.get('/api/finance/snapshot')).json();
  const category = snapshot.categories.find((c: { id: string }) => c.id === 'e_food');
  await page.goto('/#/finance/transactions');
  // The account was seeded through the API after this SPA loaded; reload the
  // provider snapshot before opening a form that captures account selections.
  await page.reload();
  await expect(page.locator('.skeleton')).toHaveCount(0);
  await page.getByRole('button', { name: '记一笔', exact: true }).last().click();
  const dialog = page.getByRole('dialog', { name: '记一笔', exact: true });
  await dialog.getByLabel('金额（元）').fill('1.23');
  await dialog.getByRole('button', { name: '下一步' }).click();
  await dialog.getByRole('radio', { name: category.name, exact: true }).click();
  await dialog.getByLabel('支付账户').selectOption(account.id);
  await dialog.getByRole('button', { name: '下一步' }).click();
  await dialog.getByLabel('备注（可选）').fill('手机闭环合成记录');
  await dialog.getByRole('button', { name: '保存', exact: true }).click();
  await expect(dialog).toBeHidden();
  expect((await (await request.get('/api/finance/snapshot')).json()).accounts.find((a: { id: string }) => a.id === account.id).balance).toBe(9877);
  await expect(page.getByText('手机闭环合成记录', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
  await page.screenshot({ path: 'test-results/finance-real-mobile.png', fullPage: true });
});
